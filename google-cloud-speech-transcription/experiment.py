#!/usr/bin/env python3
"""Generate a synthetic Japanese tech-talk clip and transcribe it.

The audio is generated by Gemini TTS, then sent to Cloud Speech-to-Text V1
with and without speech-context hints. A deterministic noisy copy is also
evaluated. The result JSON contains raw transcripts and normalized CER.
"""

from __future__ import annotations

import argparse
import array
import base64
import json
import math
import os
import random
import re
import subprocess
import time
import urllib.error
import urllib.request
import wave
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE_PATH = ROOT / "source_transcript.txt"
RESULTS_DIR = ROOT / "results"
TTS_MODEL = "gemini-2.5-flash-preview-tts"
VOICE_NAME = "Kore"
SAMPLE_RATE = 24_000
SNR_DB = 12.0
TECHNICAL_TERMS = [
    "Cloud Run",
    "Gemini",
    "Pub/Sub",
    "Cloud Logging",
    "asia-northeast1",
    "P95",
    "HTTP 429",
    "指数バックオフ",
    "SRE",
]


def post_json(url: str, payload: dict, headers: dict[str, str]) -> dict:
    request = urllib.request.Request(
        url,
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        headers={"Content-Type": "application/json", **headers},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            return json.load(response)
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code}: {detail[:1000]}") from exc


def generate_audio(output_path: Path) -> None:
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise RuntimeError("GEMINI_API_KEY is required to generate audio")

    transcript = SOURCE_PATH.read_text(encoding="utf-8").strip()
    prompt = (
        "日本語の技術カンファレンスで落ち着いて発表するように、次の原稿だけを"
        "自然な速さで読み上げてください。原稿の追加、省略、言い換えはしないでください。\n\n"
        + transcript
    )
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "responseModalities": ["AUDIO"],
            "speechConfig": {
                "voiceConfig": {
                    "prebuiltVoiceConfig": {"voiceName": VOICE_NAME}
                }
            },
        },
    }
    url = (
        "https://generativelanguage.googleapis.com/v1beta/models/"
        f"{TTS_MODEL}:generateContent"
    )
    response = post_json(url, payload, {"x-goog-api-key": api_key})
    part = response["candidates"][0]["content"]["parts"][0]
    inline_data = part.get("inlineData") or part.get("inline_data")
    if not inline_data:
        raise RuntimeError("Gemini TTS response did not contain audio")
    pcm = base64.b64decode(inline_data["data"])
    with wave.open(str(output_path), "wb") as wav_file:
        wav_file.setnchannels(1)
        wav_file.setsampwidth(2)
        wav_file.setframerate(SAMPLE_RATE)
        wav_file.writeframes(pcm)


def add_white_noise(source_path: Path, output_path: Path, snr_db: float) -> None:
    with wave.open(str(source_path), "rb") as source:
        params = source.getparams()
        if params.nchannels != 1 or params.sampwidth != 2:
            raise RuntimeError("Expected mono 16-bit PCM WAV")
        samples = array.array("h", source.readframes(params.nframes))

    signal_rms = math.sqrt(sum(sample * sample for sample in samples) / len(samples))
    noise_rms = signal_rms / (10 ** (snr_db / 20))
    random_generator = random.Random(20260911)
    noisy_samples = array.array(
        "h",
        (
            max(-32768, min(32767, round(sample + random_generator.gauss(0, noise_rms))))
            for sample in samples
        ),
    )
    with wave.open(str(output_path), "wb") as output:
        output.setparams(params)
        output.writeframes(noisy_samples.tobytes())


def gcloud_access_token() -> str:
    return subprocess.check_output(
        ["gcloud", "auth", "print-access-token"], text=True
    ).strip()


def gcloud_project() -> str:
    project = os.environ.get("GOOGLE_CLOUD_PROJECT")
    if project:
        return project
    return subprocess.check_output(
        ["gcloud", "config", "get-value", "project"], text=True
    ).strip()


def transcribe(audio_path: Path, use_hints: bool) -> tuple[str, float, dict]:
    with wave.open(str(audio_path), "rb") as wav_file:
        duration = wav_file.getnframes() / wav_file.getframerate()
    audio_content = base64.b64encode(audio_path.read_bytes()).decode("ascii")
    config: dict = {
        "encoding": "LINEAR16",
        "sampleRateHertz": SAMPLE_RATE,
        "languageCode": "ja-JP",
        "model": "latest_long",
        "enableAutomaticPunctuation": True,
    }
    if use_hints:
        config["speechContexts"] = [{"phrases": TECHNICAL_TERMS, "boost": 15}]
    payload = {"config": config, "audio": {"content": audio_content}}
    started = time.perf_counter()
    response = post_json(
        "https://speech.googleapis.com/v1/speech:recognize",
        payload,
        {
            "Authorization": f"Bearer {gcloud_access_token()}",
            "X-Goog-User-Project": gcloud_project(),
        },
    )
    elapsed = time.perf_counter() - started
    transcript = "".join(
        result["alternatives"][0].get("transcript", "")
        for result in response.get("results", [])
    )
    return transcript, elapsed, response


def normalize(text: str) -> str:
    return re.sub(r"[^0-9a-zA-Z一-龠ぁ-んァ-ヶー]", "", text).lower()


def edit_distance(left: str, right: str) -> int:
    if len(left) < len(right):
        left, right = right, left
    previous = list(range(len(right) + 1))
    for left_index, left_char in enumerate(left, start=1):
        current = [left_index]
        for right_index, right_char in enumerate(right, start=1):
            current.append(
                min(
                    current[-1] + 1,
                    previous[right_index] + 1,
                    previous[right_index - 1] + (left_char != right_char),
                )
            )
        previous = current
    return previous[-1]


def score(reference: str, hypothesis: str) -> dict:
    normalized_reference = normalize(reference)
    normalized_hypothesis = normalize(hypothesis)
    distance = edit_distance(normalized_reference, normalized_hypothesis)
    matched_terms = [
        term for term in TECHNICAL_TERMS if normalize(term) in normalized_hypothesis
    ]
    return {
        "normalized_reference_characters": len(normalized_reference),
        "edit_distance": distance,
        "cer": distance / len(normalized_reference),
        "matched_technical_terms": matched_terms,
        "technical_term_recall": len(matched_terms) / len(TECHNICAL_TERMS),
    }


def audio_metadata(audio_path: Path) -> dict:
    with wave.open(str(audio_path), "rb") as wav_file:
        return {
            "duration_seconds": wav_file.getnframes() / wav_file.getframerate(),
            "sample_rate_hz": wav_file.getframerate(),
            "channels": wav_file.getnchannels(),
            "sample_width_bytes": wav_file.getsampwidth(),
        }


def run(trials: int) -> Path:
    RESULTS_DIR.mkdir(exist_ok=True)
    clean_path = ROOT / "synthetic-tech-talk-clean.wav"
    noisy_path = ROOT / "synthetic-tech-talk-noisy.wav"
    if not clean_path.exists():
        generate_audio(clean_path)
    add_white_noise(clean_path, noisy_path, SNR_DB)

    reference = SOURCE_PATH.read_text(encoding="utf-8").strip()
    records = []
    for audio_label, audio_path in (("clean", clean_path), ("noise_12db", noisy_path)):
        for use_hints in (False, True):
            for trial in range(1, trials + 1):
                transcript, elapsed, raw_response = transcribe(audio_path, use_hints)
                records.append(
                    {
                        "audio": audio_label,
                        "hints": use_hints,
                        "trial": trial,
                        "elapsed_seconds": elapsed,
                        "transcript": transcript,
                        "score": score(reference, transcript),
                        "raw_response": raw_response,
                    }
                )

    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    output_path = RESULTS_DIR / f"speech-{timestamp}.json"
    output = {
        "created_at": datetime.now().astimezone().isoformat(),
        "speech_api": "v1 speech:recognize",
        "speech_model": "latest_long",
        "language_code": "ja-JP",
        "tts_model": TTS_MODEL,
        "tts_voice": VOICE_NAME,
        "noise_snr_db": SNR_DB,
        "trials_per_condition": trials,
        "technical_terms": TECHNICAL_TERMS,
        "reference": reference,
        "audio": {
            "clean": audio_metadata(clean_path),
            "noise_12db": audio_metadata(noisy_path),
        },
        "records": records,
    }
    output_path.write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return output_path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("run", "generate"), nargs="?", default="run")
    parser.add_argument("--trials", type=int, default=3)
    args = parser.parse_args()
    if args.command == "generate":
        generate_audio(ROOT / "synthetic-tech-talk-clean.wav")
        print(ROOT / "synthetic-tech-talk-clean.wav")
        return
    if args.trials < 1:
        parser.error("--trials must be at least 1")
    print(run(args.trials))


if __name__ == "__main__":
    main()
